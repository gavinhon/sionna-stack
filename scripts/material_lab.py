#!/usr/bin/env python
"""Material lab: one wall, one material at a time, close up (see configs/material_lab.toml).

    uv run scripts/material_lab.py configs/material_lab.toml

For "no wall" and each material it writes a tiny scene (ground + one flat wall, same material definitions as the
Singapore scene), computes a 0.25 m radio map per band and compares it with the no-wall map:
    material_lab_maps.png      signal strength, every material x band
    material_lab_effect.png    what the wall changed vs no wall: red = extra signal (reflection),
                               blue = signal removed (shadow); the key figure
    material_lab_profile.png   signal along a line through the transmitter, across the wall
    material_lab_effect.gif    the effect maps, one material per frame (for the docs)
    material_lab.csv / .md     loss behind the wall and gain in front, per material and band
    maps.npz                   all path-gain maps [dB]
into outputs/material_lab/<run_id>/ (scenes in scenes/ inside the run folder).
"""

import argparse
import dataclasses
import json
import os
import sys
import time
import tomllib
from datetime import datetime
from pathlib import Path

os.environ.setdefault("MPLBACKEND", "Agg")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

MATERIAL_NAMES = {"concrete": "concrete", "brick": "brick", "marble": "stone (marble)", "wood": "wood",
                  "glass": "glass", "metal": "metal"}


def write_scene(folder: Path, material: str | None, width: float, height: float) -> Path:
    """Ground (as in the city scene) + optionally one flat wall in the plane x = 0."""
    import trimesh
    from make_osm_scene import GROUND, MATERIAL_PROPS, MATERIAL_XML, SHAPE_XML

    (folder / "meshes").mkdir(parents=True, exist_ok=True)
    g = 80.0
    trimesh.Trimesh(vertices=[[-g, -g, 0], [g, -g, 0], [g, g, 0], [-g, g, 0]], faces=[[0, 1, 2], [0, 2, 3]]) \
        .export(folder / "meshes" / "ground.ply", encoding="binary")
    gname, gth, gs = GROUND
    xml = ['<scene version="2.1.0">\n<!-- Generated by scripts/material_lab.py -->\n',
           MATERIAL_XML.format(id="rm_ground", itu=gname, thickness=gth, s=gs),
           SHAPE_XML.format(name="ground", mat="rm_ground")]
    if material:
        th, s = MATERIAL_PROPS[material]
        w = width / 2
        # a single surface = one wall of the material's thickness (Sionna's thin-slab model); a closed box would
        # count the wall twice (entering and leaving)
        trimesh.Trimesh(vertices=[[0, -w, 0], [0, w, 0], [0, w, height], [0, -w, height]],
                        faces=[[0, 1, 2], [0, 2, 3]]).export(folder / "meshes" / "wall.ply", encoding="binary")
        xml += [MATERIAL_XML.format(id=f"rm_{material}", itu=material, thickness=th, s=s),
                SHAPE_XML.format(name="wall", mat=f"rm_{material}")]
    xml.append("</scene>\n")
    (folder / "scene.xml").write_text("".join(xml))
    return folder / "scene.xml"


def regions(xc, yc, tx, width, height, z_map):
    """Boolean masks: 'behind' = geometric shadow of the wall (>= 2 m from its edges); 'front' = cells the specular
    reflection reaches (mirror image of the TX seen through the wall), >= 3 m from the TX."""
    import numpy as np
    tx = np.asarray(tx, float)

    def crosses(src, x, y):
        t = (0.0 - src[0]) / (x - src[0])                      # where the line src -> cell meets x = 0
        yc_, zc_ = src[1] + t * (y - src[1]), src[2] + t * (z_map - src[2])
        return (t > 0) & (t < 1) & (np.abs(yc_) < width / 2 - 2) & (zc_ > 0.5) & (zc_ < height - 2)

    behind = (xc > 1.0) & crosses(tx, xc, yc)
    image = tx * np.array([-1, 1, 1])                          # mirror of the TX in the wall plane
    front = (xc < -1.0) & crosses(image, xc, yc) & (np.hypot(xc - tx[0], yc - tx[1]) > 3)
    return behind, front


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config")
    ap.add_argument("--out", default=str(ROOT / "outputs"))
    ap.add_argument("--quick", action="store_true", help="1e7 rays, 0.5 m cells (smoke test)")
    args = ap.parse_args()

    from sionna_stack import backend
    backend.init()
    import numpy as np
    from sionna_stack import experiment as ex, metrics
    from sionna_stack.config import band_label, band_slug, load_config

    cfg = load_config(args.config)
    lab = tomllib.loads(Path(args.config).read_text())["material_lab"]
    mats, width, height = lab["materials"], float(lab["wall_width"]), float(lab["wall_height"])
    if args.quick:
        cfg.radio_map.samples_per_tx = 10_000_000
        cfg.radio_map.cell_size = [0.5, 0.5]
    run = Path(args.out) / cfg.name / datetime.now().strftime("%Y%m%d-%H%M%S")
    run.mkdir(parents=True)
    tx = cfg.transmitters[0].position
    t_start = time.perf_counter()

    maps, extrap, grid = {}, {}, None
    for case in ["none"] + mats:
        scene_xml = write_scene(run / "scenes" / case, None if case == "none" else case, width, height)
        c = dataclasses.replace(cfg, scene=str(scene_xml))
        scene = ex.build_scene(c)
        for ghz in cfg.bands_ghz:
            t0 = time.perf_counter()
            bad = ex.set_band(scene, c, ghz)
            rm = ex.compute_radio_map(scene, c)
            # cells no ray reached (e.g. behind metal) are set to FLOOR_DB, so differences stay finite; a loss
            # figure that hits the floor means "at least this much"
            pg = metrics.db(np.array(rm.path_gain)[0])
            maps[(case, ghz)] = np.maximum(np.nan_to_num(pg, nan=FLOOR_DB, neginf=FLOOR_DB), FLOOR_DB).astype(np.float32)
            extrap[(case, ghz)] = [b.split(" ")[0] for b in bad]
            if grid is None:
                grid = ex.radio_map_grid(rm)
            ex._release_gpu_cache()
            print(f"  {case:>8} {band_label(ghz):>8}: {time.perf_counter() - t0:5.1f} s"
                  + (f"  (extrapolated: {', '.join(extrap[(case, ghz)])})" if bad else ""))

    cc = grid["cell_centers"]
    xc, yc = cc[..., 0], cc[..., 1]
    behind, front = regions(xc, yc, tx, width, height, cfg.radio_map.center[2])
    np.savez_compressed(run / "maps.npz", x=xc, y=yc, behind=behind, front=front,
                        **{f"{case}_{band_slug(g)}": m for (case, g), m in maps.items()})

    # ---------------------------------------------------------------- numbers
    rows = []
    for m in mats:
        for g in cfg.bands_ghz:
            d = maps[(m, g)] - maps[("none", g)]
            rows.append({
                "material": m, "band_ghz": g,
                "behind_wall_db": float(np.median(d[behind])),     # negative = signal lost behind the wall
                "in_front_db": float(np.median(d[front])),         # positive = extra signal from the reflection
                "behind_at_floor_pct": float(100 * (maps[(m, g)][behind] <= FLOOR_DB).mean()),
                "extrapolated": ", ".join(e.replace("rm_", "") for e in extrap[(m, g)]),
            })
    import pandas as pd
    df = pd.DataFrame(rows)
    df.to_csv(run / "material_lab.csv", index=False)
    lines = ["| material | " + " | ".join(f"{band_label(g)}: behind / in front" for g in cfg.bands_ghz) + " |",
             "|---|" + "---|" * len(cfg.bands_ghz)]
    for m in mats:
        cells = []
        for g in cfg.bands_ghz:
            r = df[(df.material == m) & (df.band_ghz == g)].iloc[0]
            star = "*" if r.extrapolated and m in r.extrapolated.split(", ") else ""
            le = "≤ " if r.behind_at_floor_pct > 50 else ""
            cells.append(f"{le}{r.behind_wall_db:+.1f} dB / {r.in_front_db:+.1f} dB{star}")
        lines.append(f"| {MATERIAL_NAMES[m]} | " + " | ".join(cells) + " |")
    lines.append("\n\\* ITU-R P.2040 has no data for this material at this band: extrapolated.  "
                 "≤: most of the shadow zone received no ray at all, so the loss is at least this much.")
    (run / "material_lab.md").write_text("\n".join(lines) + "\n")
    print("\n" + "\n".join(lines))

    figures(run, cfg, mats, maps, xc, yc, behind, front, df, tx, width)
    man = {"experiment": cfg.name, "run_id": run.name, "config": str(Path(args.config).resolve()),
           "bands_ghz": cfg.bands_ghz, "materials": mats, "wall": {"width_m": width, "height_m": height},
           "tx": tx, "radio_map": dataclasses.asdict(cfg.radio_map), "backend": backend.info().as_dict(),
           "floor_db": FLOOR_DB,
           "extrapolated": {f"{c}@{g}": v for (c, g), v in extrap.items() if v},
           "duration_s": round(time.perf_counter() - t_start, 1)}
    (run / "manifest.json").write_text(json.dumps(man, indent=2, default=str))
    latest = run.parent / "latest"
    latest.unlink(missing_ok=True)
    latest.symlink_to(run.name)
    print(f"\n-> {run}")
    return 0


def figures(run, cfg, mats, maps, xc, yc, behind, front, df, tx, width):
    import matplotlib.pyplot as plt
    import numpy as np
    from matplotlib.animation import FuncAnimation, PillowWriter
    from matplotlib.colors import TwoSlopeNorm
    from sionna_stack.config import band_label

    bands = cfg.bands_ghz
    rc = cfg.radio_map
    ext = [xc.min(), xc.max(), yc.min(), yc.max()]

    def deco(ax, show_regions=False, wall=True):
        if wall:
            ax.plot([0, 0], [-width / 2, width / 2], color="black", lw=3, solid_capstyle="butt")
        ax.plot(*tx[:2], "o", color="red", ms=6, mec="white", mew=1)
        if show_regions:
            ax.contour(xc, yc, behind.astype(float), [0.5], colors="k", linewidths=0.6, linestyles=":")
            ax.contour(xc, yc, front.astype(float), [0.5], colors="k", linewidths=0.6, linestyles="--")
        ax.set_xlim(ext[0], ext[1]); ax.set_ylim(ext[2], ext[3])
        ax.set_aspect("equal"); ax.set_xticks([]); ax.set_yticks([])

    def label(m):
        return MATERIAL_NAMES.get(m, "no wall")

    # 1. signal maps
    cases = ["none"] + mats
    fig, axes = plt.subplots(len(cases), len(bands), figsize=(3.3 * len(bands) + 1, 2.75 * len(cases)),
                             constrained_layout=True, squeeze=False)
    for i, c in enumerate(cases):
        for j, g in enumerate(bands):
            ax = axes[i, j]
            im = ax.pcolormesh(xc, yc, maps[(c, g)], vmin=rc.vmin_db, vmax=rc.vmax_db, cmap="viridis", shading="nearest")
            deco(ax, wall=c != "none")
            if i == 0:
                ax.set_title(band_label(g), fontsize=12)
            if j == 0:
                ax.set_ylabel(label(c), fontsize=11)
    fig.colorbar(im, ax=axes, shrink=0.5, label="path gain [dB]")
    fig.suptitle("Material lab: signal strength at 1.5 m around one wall (black line); red dot = transmitter\n"
                 "top row: no wall. 50 m x 40 m, 0.25 m cells", fontsize=11)
    fig.savefig(run / "material_lab_maps.png", dpi=110)
    plt.close(fig)

    # 2. effect of the wall (difference to no wall)
    def effect_panel(ax, m, g, annotate=True):
        d = maps[(m, g)] - maps[("none", g)]
        # blue down to -40 dB (removed), red up to +6 dB (added): a reflection adds at most ~+3 dB where the
        # transmitter is also seen directly, so a symmetric scale would hide it
        im = ax.pcolormesh(xc, yc, d, norm=TwoSlopeNorm(vmin=-40, vcenter=0, vmax=6), cmap="RdBu_r",
                           shading="nearest")
        deco(ax, show_regions=True)
        if annotate:
            r = df[(df.material == m) & (df.band_ghz == g)].iloc[0]
            ax.text(0.98, 0.03, f"behind {r.behind_wall_db:+.0f} dB", transform=ax.transAxes, ha="right",
                    fontsize=9, color="black", bbox=dict(fc="white", alpha=0.75, lw=0, pad=1.5))
            ax.text(0.02, 0.03, f"front {r.in_front_db:+.1f} dB", transform=ax.transAxes, ha="left",
                    fontsize=9, color="black", bbox=dict(fc="white", alpha=0.75, lw=0, pad=1.5))
        return im

    fig, axes = plt.subplots(len(mats), len(bands), figsize=(3.3 * len(bands) + 1, 2.75 * len(mats)),
                             constrained_layout=True, squeeze=False)
    for i, m in enumerate(mats):
        for j, g in enumerate(bands):
            im = effect_panel(axes[i, j], m, g)
            if i == 0:
                axes[i, j].set_title(band_label(g), fontsize=12)
            if j == 0:
                axes[i, j].set_ylabel(label(m), fontsize=11)
    cb = fig.colorbar(im, ax=axes, shrink=0.5, label="change vs no wall [dB]  (red = more signal, blue = less)")
    cb.set_ticks([-40, -30, -20, -10, 0, 3, 6])
    fig.suptitle("What the wall changes, by material: blue = signal the wall removes (shadow behind it),\n"
                 "red = signal it adds (reflection in front). Dotted: shadow zone, dashed: reflection zone",
                 fontsize=11)
    fig.savefig(run / "material_lab_effect.png", dpi=110)
    plt.close(fig)

    # 3. profile along the line through the transmitter, perpendicular to the wall
    j0 = int(np.argmin(np.abs(yc[:, 0] - tx[1])))
    x = xc[j0, :]
    fig, axes = plt.subplots(1, len(bands), figsize=(5.2 * len(bands), 4), constrained_layout=True, sharey=True)
    for ax, g in zip(np.atleast_1d(axes), bands):
        ax.plot(x, maps[("none", g)][j0, :], color="black", ls="--", lw=1.4, label="no wall")
        for k, m in enumerate(mats):
            ax.plot(x, maps[(m, g)][j0, :], color=MAT_COLORS[m], lw=1.3, label=label(m))
        ax.axvline(0, color="gray", lw=3, alpha=0.5)
        ax.text(0.3, rc.vmax_db - 4, "wall", color="gray", fontsize=9)
        ax.set_title(band_label(g))
        ax.set_xlabel("distance along the line through the transmitter [m] (wall at 0)")
        ax.set_ylim(rc.vmin_db, rc.vmax_db)
        ax.grid(alpha=0.3)
    np.atleast_1d(axes)[0].set_ylabel("path gain at 1.5 m [dB]")
    handles, labels = np.atleast_1d(axes)[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", ncol=len(labels), fontsize=9)
    fig.suptitle("Across the wall: the drop at x = 0 is what each material lets through; left of it, the reflection adds signal")
    fig.savefig(run / "material_lab_profile.png", dpi=120)
    plt.close(fig)

    # 4. GIF: one material per frame, all bands side by side
    fig, axes = plt.subplots(1, len(bands), figsize=(3.4 * len(bands), 3.4), constrained_layout=True)
    axes = np.atleast_1d(axes)

    def draw(i):
        m = mats[i]
        for ax, g in zip(axes, bands):
            ax.clear()
            effect_panel(ax, m, g)
            ax.set_title(band_label(g))
        fig.suptitle(f"Wall material: {label(m).upper()}   (blue = signal removed, red = signal added vs no wall)",
                     fontsize=11)

    FuncAnimation(fig, draw, frames=len(mats)).save(run / "material_lab_effect.gif", writer=PillowWriter(fps=0.6),
                                                     dpi=90)
    plt.close(fig)


FLOOR_DB = -160.0  # path gain assigned to cells no ray reached
MAT_COLORS = {"concrete": "#8d8d8d", "brick": "#b5523b", "marble": "#c9b98f", "wood": "#8a5a2b",
              "glass": "#3aa0d8", "metal": "#4b4f9c"}

if __name__ == "__main__":
    raise SystemExit(main())
